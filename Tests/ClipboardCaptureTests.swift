import AppKit

@main struct ClipboardCaptureTests {
    @MainActor static func main() throws {
        _ = NSApplication.shared
        NSApp.setActivationPolicy(.prohibited)
        let board = NSPasteboard.withUniqueName()
        let target = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally(); target.releaseGlobally() }
        var failures = 0
        func check(_ value: Bool, _ label: String) {
            print("\(value ? "PASS" : "FAIL") \(label)"); if !value { failures += 1 }
        }
        func put(_ string: String, mark: String? = nil) {
            board.clearContents()
            let item = NSPasteboardItem(); item.setString(string, forType: .string)
            if let mark { item.setString("", forType: .init(mark)) }
            board.writeObjects([item])
        }
        put("History fixture 中文")
        let text = ClipboardCapture.read(board)
        check(text?.text == "History fixture 中文", "a real private pasteboard yields searchable text")
        if let text {
            check(ClipboardCapture.write(text, to: target) && target.string(forType: .string) == text.text,
                  "selecting history restores exact text to a separate pasteboard")
        } else { check(false, "selecting history restores exact text to a separate pasteboard") }
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            put("private fixture", mark: type)
            check(ClipboardCapture.read(board) == nil, "sensitive or temporary marker is never persisted: \(type)")
        }
        put(" \n ")
        check(ClipboardCapture.read(board) == nil, "empty text is ignored")
        let image = NSImage(size: NSSize(width: 32, height: 24))
        image.lockFocus(); NSColor.red.setFill(); NSRect(x: 0, y: 0, width: 32, height: 24).fill(); image.unlockFocus()
        let png = NSBitmapImageRep(data: image.tiffRepresentation!)!.representation(using: .png, properties: [:])!
        board.clearContents(); board.setData(png, forType: .png)
        let screenshot = ClipboardCapture.read(board)
        check(screenshot?.imageData == png, "screenshots are captured as their original PNG bytes")
        if let screenshot {
            check(ClipboardCapture.write(screenshot, to: target) && target.data(forType: .png) == png,
                  "history images paste back as image data")
        } else { check(false, "history images paste back as image data") }
        let item1 = NSPasteboardItem(); item1.setString("first", forType: .string)
        let item2 = NSPasteboardItem(); item2.setString("second", forType: .string)
        board.clearContents(); board.writeObjects([item1, item2])
        let multiple = ClipboardCapture.read(board)
        check(multiple?.items.count == 2, "multi-item copies retain item boundaries")
        if let multiple {
            _ = ClipboardCapture.write(multiple, to: target)
            check(target.pasteboardItems?.map { $0.string(forType: .string) ?? "" } == ["first", "second"],
                  "restoring multiple clipboard items does not merge or duplicate them")
        } else { check(false, "restoring multiple clipboard items does not merge or duplicate them") }
        put("same"); let one = ClipboardCapture.read(board)
        put("same"); let two = ClipboardCapture.read(board)
        check(one != nil && one?.fingerprint == two?.fingerprint, "identical copies have stable content identities")
        let html = NSPasteboardItem(); html.setString("link", forType: .string)
        html.setString("<b>link</b>", forType: .html)
        html.setData(Data([1,2,3]), forType: .init("com.apple.webarchive"))
        board.clearContents(); board.writeObjects([html])
        let rich = ClipboardCapture.read(board)
        check(rich?.items.first?.contains(where: { $0.type == NSPasteboard.PasteboardType.html.rawValue }) == true,
              "rich text formatting is retained")
        check(rich?.items.first?.contains(where: { $0.type == "com.apple.webarchive" }) == false,
              "large browser archives are not captured")
        put("fixture", mark: ClipboardCapture.ownType.rawValue)
        check(ClipboardCapture.read(board) == nil, "re-copying history cannot recursively create records")
        board.clearContents()
        board.setData(Data(repeating: 65, count: ClipboardCapture.maximumItemBytes + 1), forType: .string)
        check(ClipboardCapture.read(board) == nil, "oversized clipboard payloads are bounded")
        if failures > 0 { print("\(failures) clipboard checks failed"); exit(1) }
        print("All clipboard capture checks passed; system clipboard untouched")
    }
}
