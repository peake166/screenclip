import AppKit
import CryptoKit

struct ClipboardRepresentation: Codable, Equatable {
    let type: String
    let data: Data
}

struct ClipboardSnapshot: Codable, Equatable {
    let items: [[ClipboardRepresentation]]
    var byteCount: Int { items.flatMap { $0 }.reduce(0) { $0 + $1.data.count } }
    var text: String {
        items.compactMap { item in
            item.first(where: { $0.type == NSPasteboard.PasteboardType.string.rawValue })
                .flatMap { String(data: $0.data, encoding: .utf8) }
        }.joined(separator: "\n")
    }
    var imageData: Data? {
        items.flatMap { $0 }.first(where: { $0.type == NSPasteboard.PasteboardType.png.rawValue
            || $0.type == NSPasteboard.PasteboardType.tiff.rawValue })?.data
    }
    var fingerprint: String {
        let encoder = PropertyListEncoder(); encoder.outputFormat = .binary
        return SHA256.hash(data: (try? encoder.encode(self)) ?? Data()).map { String(format: "%02x", $0) }.joined()
    }
}

enum ClipboardCapture {
    static let maximumItemBytes = 16 * 1024 * 1024
    static let ownType = NSPasteboard.PasteboardType("com.local.screenclip.history-copy")
    // Maccy checks both board-wide types and individual items before reading payloads.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "org.keepassxc.KeePassXC", ownType.rawValue
    ]
    private static let supportedTypes: Set<NSPasteboard.PasteboardType> = [.string, .png, .tiff, .html, .rtf, .fileURL]

    static func read(_ board: NSPasteboard) -> ClipboardSnapshot? {
        let count = board.changeCount
        guard ignoredTypes.isDisjoint(with: (board.types ?? []).map(\.rawValue)),
              let originals = board.pasteboardItems, !originals.isEmpty, originals.count <= 16 else { return nil }
        var result: [[ClipboardRepresentation]] = []
        var bytes = 0
        for item in originals {
            guard ignoredTypes.isDisjoint(with: item.types.map(\.rawValue)) else { return nil }
            var types = Set(item.types).intersection(supportedTypes)
            // PNG is lossless and usually far smaller than a duplicate TIFF representation.
            if types.contains(.png) { types.remove(.tiff) }
            var values: [ClipboardRepresentation] = []
            for type in types.sorted(by: { $0.rawValue < $1.rawValue }) {
                guard let data = item.data(forType: type), !data.isEmpty else { continue }
                bytes += data.count
                guard bytes <= maximumItemBytes else { return nil }
                values.append(ClipboardRepresentation(type: type.rawValue, data: data))
            }
            if values.allSatisfy({ $0.type == NSPasteboard.PasteboardType.string.rawValue }),
               item.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty != false { continue }
            if !values.isEmpty { result.append(values) }
        }
        guard board.changeCount == count, !result.isEmpty else { return nil }
        return ClipboardSnapshot(items: result)
    }

    @discardableResult static func write(_ snapshot: ClipboardSnapshot, to board: NSPasteboard) -> Bool {
        guard !snapshot.items.isEmpty, snapshot.byteCount <= maximumItemBytes else { return false }
        let objects = snapshot.items.map { values -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for value in values { item.setData(value.data, forType: .init(value.type)) }
            item.setString("", forType: ownType)
            return item
        }
        board.clearContents()
        return board.writeObjects(objects)
    }
}
